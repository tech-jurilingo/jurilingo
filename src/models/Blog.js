
import mongoose from "mongoose";

// Schema for blog comments
const CommentSchema = new mongoose.Schema({
  user: {
    type: mongoose.Schema.Types.ObjectId,
    ref: "User",
    required: true,
  },
  text: {
    type: String,
    required: true,
    maxlength: 2000,
  },
  createdAt: {
    type: Date,
    default: Date.now,
  },
});

// Main blog schema
const BlogSchema = new mongoose.Schema({
  title: {
    type: String,
    required: true,
    trim: true,
  },
  author: {
    type: String,
    required: true,
  },
  content: {
    type: String,
    required: true,
  },
  publishDate: {
    type: Date,
    default: Date.now,
  },
  createdAt: {
    type: Date,
    default: Date.now,
  },
  updatedAt: {
    type: Date,
    default: Date.now,
  },
  likes: {
    type: [
      {
        type: mongoose.Schema.Types.ObjectId,
        ref: "User",
      },
    ],
    default: [],
  },
  viewCount: {
    type: Number,
    default: 0,
    min: 0,
  },
  comments: {
    type: [CommentSchema],
    default: [],
  },
});

// Prevent model recompilation in Next.js
const Blog =
  mongoose.models.Blog ||
  mongoose.model("Blog", BlogSchema);

export default Blog;
